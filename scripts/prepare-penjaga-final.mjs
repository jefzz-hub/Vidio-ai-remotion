import {existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync, copyFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const media = /\.(mp3|wav|m4a|aac|ogg|flac)$/i;
const walk = (dir) => existsSync(dir) ? readdirSync(dir, {withFileTypes: true}).flatMap(e => {
  if (['node_modules', '.git', 'out', 'build', 'dist', 'work', 'penjaga-lilin-final'].includes(e.name)) return [];
  const p = path.join(dir, e.name);
  return e.isDirectory() ? walk(p) : [p];
}) : [];
const source = walk(path.join(root, 'src')).filter(p => /\.[jt]sx?$/.test(p));
const mentioned = new Set(source.flatMap(p => [...readFileSync(p, 'utf8').matchAll(/["'`]([^"'`\n]+\.(?:mp3|wav|m4a|aac|ogg|flac))["'`]/gi)].map(m => path.basename(m[1]))));
const all = ['public', 'assets', 'files'].flatMap(dir => walk(path.join(root, dir))).filter(p => media.test(p));
const preferred = all.filter(p => mentioned.has(path.basename(p)) && /hor|lilin|ambient|atmos|creep|dark|tension/i.test(p));
const named = all.filter(p => /hor|lilin|ambient|atmos|creep|dark|tension/i.test(p));
let selected = process.env.PENJAGA_AUDIO ? path.resolve(root, process.env.PENJAGA_AUDIO) : null;
if (!selected) selected = preferred.length === 1 ? preferred[0] : named.length === 1 ? named[0] : all.length === 1 ? all[0] : null;
const cfg = path.join(root, 'src/PenjagaLilinFinal/audio-config.ts');
let audio = null;
if (selected) {
  if (!existsSync(selected)) throw new Error(`Audio tidak ditemukan: ${selected}`);
  if (selected.startsWith(path.join(root, 'public') + path.sep)) audio = path.relative(path.join(root, 'public'), selected).split(path.sep).join('/');
  else {
    audio = `penjaga-lilin-final/original-atmosphere${path.extname(selected)}`;
    mkdirSync(path.dirname(path.join(root, 'public', audio)), {recursive: true});
    copyFileSync(selected, path.join(root, 'public', audio));
  }
} else if (existsSync(cfg)) {
  const previous = readFileSync(cfg, 'utf8').match(/= ("[^"]+")/);
  if (previous && existsSync(path.join(root, 'public', JSON.parse(previous[1])))) audio = JSON.parse(previous[1]);
}
writeFileSync(cfg, `// Generated by prepare-penjaga-final.mjs. Original recording; no substitute.\nexport const originalAtmosphere: string | null = ${JSON.stringify(audio)};\n`);
console.log(audio ? `Audio asli: ${audio}` : 'PERHATIAN: audio asli belum tersedia. Preview/render saat ini TANPA AUDIO. Tidak ada audio pengganti.');
if (!audio && all.length > 1) console.log('Ada beberapa audio; pilih dengan PENJAGA_AUDIO=public/nama-audio.mp3 npm run render:final');
